const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../site/app.js'),'utf8');
const ctx={document:{readyState:'loading',addEventListener(){}},console,URL};
vm.runInNewContext(src+';this.testing={escapeHtml,validHttpLink,forecastHorizon};',ctx);
const {escapeHtml,validHttpLink,forecastHorizon}=ctx.testing;
assert.equal(escapeHtml('<script>'), '&lt;script&gt;');
assert.equal(validHttpLink('javascript:alert(1)'), '');
assert.equal(forecastHorizon('1Y'),60);
assert.equal(forecastHorizon('1M'),10);
assert.ok(src.includes('ChartResearch.model(historical.points'), 'Overview delegates to the same shared source-verified model');
assert.ok(src.includes('ChartResearch.model(historic.points'), 'Price Forecasts uses the shared model');
assert.ok(src.includes('ChartResearch.walkForward(historic.points,5)'));
assert.ok(src.includes('ChartResearch.walkForward(historic.points,20)'));
assert.ok(!src.includes('function forecastMath('),'Old flat-trajectory model must not remain as a diverging implementation');
assert.ok(src.includes('The full chart shows the uncertainty range'));
console.log('Forecast v1.6.4: shared model, dual-horizon rolling checks, clear provenance and link security: PASS');
