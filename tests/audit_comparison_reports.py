#!/usr/bin/env python3
"""Offline browser acceptance for v1.7; all values are synthetic fixtures, never live market values."""
import sys,json,re
from pathlib import Path
from playwright.sync_api import sync_playwright
sys.path.insert(0,str(Path(__file__).resolve().parent))
from audit_browser import ROOT,SITE,FAKE_JS
CSS=['styles.css','tape.css','signal.css','pro.css','terminal.css','research-v17.css','research-v18.css']
JS=['market-hours.js','chart-research.js','tape.js','compare.js','reports.js','macro.js','app.js','signal.js','pro.js','terminal.js']
html=(SITE/'index.html').read_text()
html=re.sub(r'<script[^>]+src="/[^\"]+"[^>]*></script>','',html)
html=re.sub(r'<link rel="stylesheet" href="/[^\"]+">','',html)
html=html.replace('</head>','<style>'+'\n'.join((SITE/f).read_text() for f in CSS)+'</style></head>')
checks=[]
def ok(name,check=True):
 assert check,name
 checks.append(name);print('PASS',name,flush=True)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1512,'height':982},accept_downloads=True)
 errors=[];page.on('pageerror',lambda err:errors.append(str(err)))
 page.set_content(html,wait_until='domcontentloaded');page.evaluate(FAKE_JS)
 for name in JS:page.add_script_tag(content=(SITE/name).read_text())
 page.wait_for_timeout(1200)
 page.locator('[data-view="comparison"]').click();ok('Comparison view available',page.locator('#view-comparison').is_visible())
 ok('Two preselected distinct peers',page.locator('#compare-a').input_value()!=page.locator('#compare-b').input_value())
 page.locator('#compare-c').select_option('NVDA')
 page.locator('#compare-run').click();page.wait_for_timeout(600)
 ok('Comparison matrix renders three companies',page.locator('.compare-table thead th').count()==4)
 ok('Real provider endpoints sourced', 'Finnhub /stock/profile2' in page.locator('.compare-foot').inner_text())
 ok('Missing ratios explicitly labelled',page.locator('.compare-na').count()>5)
 page.locator('#compare-to-report').click()
 ok('Comparison creates report draft',page.locator('#view-reports').is_visible() and 'peer comparison' in page.locator('#report-title').input_value())
 ok('Comparison copies factual observations and sources', 'Finnhub' in page.locator('#report-financial').input_value() and 'Finnhub' in page.locator('#report-sources').input_value())
 page.locator('#report-summary').fill('Competitive advantage thesis — requires further investigation.')
 page.locator('#report-business').fill('This is a user-authored simulated case.')
 page.locator('#report-risks').fill('Demand risk and counterarguments.')
 page.locator('#report-primary').check()
 page.locator('#report-counter').check()
 page.locator('#report-save').click()
 ok('Saved research report visible in library',page.locator('.report-library-item').count()==1)
 ok('Saved content preserved in rendered report', 'Competitive advantage thesis' in page.locator('.report-document').inner_text())
 page.locator('#report-new').click();ok('New report clears fields',page.locator('#report-title').input_value()=='')
 page.locator('[data-report-open]').click();ok('Saved report loads for editing', 'peer comparison' in page.locator('#report-title').input_value())
 page.locator('#report-summary').fill('An edited research thesis.')
 page.locator('#report-save').click()
 ok('Editing updates instead of duplicating',page.locator('.report-library-item').count()==1 and 'An edited research thesis.' in page.locator('.report-document').inner_text())
 with page.expect_download(timeout=6000) as downloadinfo:page.locator('#report-export-md').click()
 download=downloadinfo.value
 file=download.path();content=Path(file).read_text()
 ok('Markdown report export contains authored sections',download.suggested_filename.endswith('.md') and 'An edited research thesis.' in content and 'References & source dates' in content)
 page.locator('#report-summary').fill('<script>document.documentElement.dataset.injected=1</script>')
 page.locator('#report-preview').click()
 ok('User-authored HTML safely escaped',page.locator('#report-preview-content script').count()==0 and page.evaluate('document.documentElement.dataset.injected') is None)
 page.locator('#report-save').click()
 backup=page.evaluate('JSON.parse(localStorage.getItem("md-reborn-reports"))')
 ok('Report persists in local storage',len(backup)==1)
 page.locator('[data-view="settings"]').click()
 with page.expect_download(timeout=6000) as dl:page.locator('#export-workspace').click()
 data=json.loads(Path(dl.value.path()).read_text())
 ok('Research report included in full backup','reports' in data['snapshot'] and len(data['snapshot']['reports'])==1)
 ok('Provider API keys excluded from backup','TEST_ONLY_NOT_REAL_KEY' not in json.dumps(data))
 page.evaluate('localStorage.setItem("md-reborn-reports","[]")')
 page.locator('#import-workspace').set_input_files({'name':'MarketDesk-Research-Backup.json','mimeType':'application/json','buffer':json.dumps(data).encode('utf-8')})
 page.wait_for_timeout(250)
 ok('Import restores report archive',len(page.evaluate('JSON.parse(localStorage.getItem("md-reborn-reports"))'))==1)
 page.set_viewport_size({'width':390,'height':844});page.locator('#menu-toggle').click();page.locator('[data-view="comparison"]').click()
 ok('Mobile Comparison workspace works',page.locator('#view-comparison').is_visible())
 ok('No browser exceptions',not errors)
 page.set_viewport_size({'width':1512,'height':982});page.locator('#compare-run').click();page.wait_for_timeout(200);page.evaluate('window.scrollTo(0,0)');page.wait_for_timeout(80)
 page.screenshot(path='/mnt/data/MarketDesk-v1.7-Comparison-Preview.png',full_page=False)
 page.locator('[data-view="reports"]').click();page.evaluate('window.scrollTo(0,0)');page.screenshot(path='/mnt/data/MarketDesk-v1.7-Reports-Preview.png',full_page=False)
 browser.close()
print('V1.7 SUMMARY:',len(checks),'checks passed; browser JS errors:',len(errors))
