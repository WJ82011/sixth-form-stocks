const assert=require('node:assert/strict');
const M=require('../site/v19-models.js');
const DAY=86400000,now=Date.now();
const series=Array.from({length:100},(_,i)=>({t:now-(99-i)*DAY,p:100+i}));
const v=M.indicators(series),last=v.at(-1);
assert.equal(v.length,100);assert.equal(v[18].sma20,null);assert.equal(v[19].sma20,109.5);
assert.equal(last.sma20,189.5);assert.equal(last.sma50,174.5);assert.equal(last.rsi14,100);
assert.equal(M.indicators(series.map(p=>({...p,p:100}))).at(-1).rsi14,50);
assert.equal(M.indicators(series.slice(0,10)).at(-1).sma20,null);
const d=M.dcf({fcf:100,growth:5,discount:10,terminal:2,shares:50,netDebt:100});
assert.ok(Math.abs(d.perShare-26.9242377997)<1e-8);assert.equal(d.forecast.length,5);
const sens=M.sensitivity({fcf:100,growth:5,discount:10,terminal:2,shares:50,netDebt:100});
assert.equal(sens.values.length,3);assert.equal(sens.values[0].length,3);
assert.equal(sens.values[1][1],d.perShare);
assert.throws(()=>M.dcf({fcf:100,growth:5,discount:4,terminal:4,shares:50,netDebt:100}),/Discount rate/);
assert.throws(()=>M.dcf({fcf:100,growth:5,discount:10,terminal:2,shares:0,netDebt:100}),/Enter valid/);
assert.throws(()=>M.dcf({fcf:NaN,growth:5,discount:10,terminal:2,shares:50,netDebt:100}),/Enter valid/);
const buy={symbol:'AAPL',side:'BUY',qty:5,price:100,date:'2026-11-02'};
const sell={symbol:'AAPL',side:'SELL',qty:2,price:120,date:'2026-11-02'};
const paper=M.portfolio(10000,[buy,sell],{AAPL:{price:110,source:'Finnhub',time:now}});
assert.equal(paper.cash,9740);assert.equal(paper.positions[0].qty,3);assert.equal(paper.positions[0].realized,40);
assert.equal(paper.totalValue,10070);assert.equal(paper.pnl,70);
assert.equal(M.portfolio(10000,[buy],{}).totalValue,null);
assert.throws(()=>M.portfolio(10000,[sell],{}),/Cannot sell more/);
assert.throws(()=>M.portfolio(100,[buy],{}),/Not enough virtual cash/);
assert.throws(()=>M.portfolio(10000,[{...buy,price:Infinity}],{}),/Invalid paper trade/);
console.log('PASS v1.9 models: technical signals, DCF cases, sensitivity and simulation safeguards');
